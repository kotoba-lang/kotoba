#!/usr/bin/env python3
"""Emit public BLAKE2s/HMAC known answers using Python's independent hashlib.

Development fixture generator only; the native guest executes every assertion.
No runtime fallback. Usage: gen_blake2s_gate.py OUTPUT
"""
import hashlib
import hmac
import sys


def data(n):
    return bytes(i % 256 for i in range(n))


def lit(value):
    return '(vector-i64 ' + ' '.join(map(str, value)) + ')'


corpus = b''.join(hashlib.blake2s(data(n)).digest() for n in range(258))
macs = b''.join(hmac.digest(data(n), data(129), 'blake2s') for n in (0, 32, 64, 65, 100))
source = ''';; Public oracle fixtures: RFC 7693 abc + Python hashlib/HMAC corpus.
;; Generated by tools/gen_blake2s_gate.py; no host hashing during native execution.
(ns noise.blake2s-gate (:require [noise.blake2s-native :as b]) (:export [main]))
(defn- same? [a :vector-i64 c :vector-i64] :bool
  (and (= (vector-count a) (vector-count c))
    (loop [i 0] (if (= i (vector-count a)) true
      (if (= (vector-at a i) (vector-at c i)) (recur (+ i 1)) false)))))
(defn- data [n :i64] :vector-i64
  (loop [i 0 out (vector-alloc n)] (if (= i n) out
    (recur (+ i 1) (vector-assoc! out i (rem i 256))))))
(defn- key-size [i :i64] :i64 (case i 0 0 1 32 2 64 3 65 100))
(defn- corpus [] :vector-i64
  (let [out (vector-alloc 8256)
        filled (loop [n 0] (if (= n 258) 0
          (let [d (b/digest (data n))
                copied (loop [j 0] (if (= j 32) 0
                  (let [p (vector-assoc! out (+ (* n 32) j) (vector-at d j))] (recur (+ j 1)))))]
            (recur (+ n 1)))))] (b/digest out)))
(defn- macs [] :vector-i64
  (let [out (vector-alloc 160)
        filled (loop [i 0] (if (= i 5) 0
          (let [d (b/hmac (data (key-size i)) (data 129))
                copied (loop [j 0] (if (= j 32) 0
                  (let [p (vector-assoc! out (+ (* i 32) j) (vector-at d j))] (recur (+ j 1)))))]
            (recur (+ i 1)))))] (b/digest out)))
(defn main [] :i64
  (+ (if (same? (b/digest (vector-i64 97 98 99)) ABC) 1 0)
     (if (same? (b/digest (vector-i64)) EMPTY) 2 0)
     (if (same? (corpus) CORPUS) 4 0)
     (if (same? (macs) MACS) 8 0)
     (if (and (= (vector-count (b/digest (vector-i64 -1))) 0)
              (= (vector-count (b/digest (vector-i64 256))) 0)
              (= (vector-count (b/hmac (vector-i64 256) (vector-i64))) 0)
              (= (vector-count (b/hmac (vector-i64) (vector-i64 -1))) 0)) 16 0)))
'''
for token, value in [('ABC', hashlib.blake2s(b'abc').digest()),
                     ('EMPTY', hashlib.blake2s(b'').digest()),
                     ('CORPUS', hashlib.blake2s(corpus).digest()),
                     ('MACS', hashlib.blake2s(macs).digest())]:
    source = source.replace(token, lit(value))
with open(sys.argv[1], 'w') as output:
    output.write(source)
