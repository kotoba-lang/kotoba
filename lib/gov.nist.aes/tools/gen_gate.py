#!/usr/bin/env python3
"""Write kotoba/aes/native_gate.kotoba from Wycheproof AES-GCM cases and FIPS 197.

Dev tool, not part of the library. Standard library only.

    python3 -I tools/gen_gate.py kotoba/aes/native_gate.kotoba

The cases come from test/aes/wycheproof_gcm.cljk (the whole corpus, sha256 recorded
there). Every chosen case is re-checked against tools/reference.py before it is
written. Bytes are vector literals of at most 64 items; there are no strings.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from reference import _j0, encrypt_block, open_, seal  # noqa: E402

h = bytes.fromhex
cases = []
for line in open(os.path.join(os.path.dirname(HERE), 'test', 'aes', 'wycheproof_gcm.cljk')):
    if ':key "' not in line:
        continue
    c = {k: h(v) for k, v in re.findall(r':(key|msg|iv|aad|tag|ct) "([0-9a-f]*)"', line)}
    c['valid'] = ':result :valid' in line
    c['id'] = int(re.search(r':id (\d+)', line).group(1))
    c['flags'] = set(re.findall(r':(\w+)', re.search(r':flags #\{([^}]*)\}', line).group(1)))
    cases.append(c)
assert len(cases) == 316

def wrapping(per_key):
    # counter-wrap cases whose 32-bit counter starts at 2^32 - 1, - 2 and - 3, so the wrap
    # falls at J0 -> inc32(J0) and inside the GCTR loop
    out = []
    for ks in (16, 24, 32):
        for start in (0xffffffff, 0xfffffffe, 0xfffffffd)[:per_key]:
            out.append(next(c for c in cases if 'CounterWrap' in c['flags'] and len(c['key']) == ks
                            and int.from_bytes(_j0(c['key'], c['iv'])[1][12:], 'big') == start))
    return out

def pick(flag, per_key, max_msg=64):
    out = []
    for ks in (16, 24, 32):
        got = [c for c in cases if flag in c['flags'] and len(c['key']) == ks and len(c['msg']) <= max_msg]
        out += got[:per_key]
    return out

GROUPS = {
    'a': [('Ktv', pick('Ktv', 7)), ('Pseudorandom', pick('Pseudorandom', 4))],
    'b': [('SmallIv', pick('SmallIv', 2)), ('LongIv', pick('LongIv', 2)), ('SpecialCase', pick('SpecialCase', 2))],
    'c': [('CounterWrap', wrapping(3)), ('ModifiedTag', pick('ModifiedTag', 3)), ('ZeroLengthIv', pick('ZeroLengthIv', 2))],
}
for grp in GROUPS.values():
    for flag, cs in grp:
        assert cs, flag
        for c in cs:
            if c['valid']:
                assert seal(c['key'], c['iv'], c['aad'], c['msg']) == c['ct'] + c['tag'], c['id']
            else:
                assert open_(c['key'], c['iv'], c['aad'], c['ct'] + c['tag']) is None, c['id']

PT = h('00112233445566778899aabbccddeeff')
FIPS = [(h('000102030405060708090a0b0c0d0e0f'), '69c4e0d86a7b0430d8cdb78070b4c55a'),
        (h('000102030405060708090a0b0c0d0e0f1011121314151617'), 'dda97ca4864cdfe06eaf70a0ec0d7191'),
        (bytes(range(32)), '8ea2b7ca516745bfeafc49904b496089')]
for k, out in FIPS:
    assert encrypt_block(k, PT).hex() == out

def lit(b):
    b = list(b)
    if not b:
        return '(vector-i64)'
    parts = [f'(vector-i64 {" ".join(map(str, b[i:i + 64]))})' for i in range(0, len(b), 64)]
    while len(parts) > 1:
        parts = [f'(cat {parts[i]} {parts[i + 1]})' if i + 1 < len(parts) else parts[i] for i in range(0, len(parts), 2)]
    return parts[0]

defs, bodies = [], {}
for grp, flags in GROUPS.items():
    terms = []
    for bit, (flag, cs) in enumerate(flags):
        checks = []
        for c in cs:
            n = f'g-{c["id"]}'
            for f in ('key', 'iv', 'aad', 'msg'):
                defs.append(f'(defn- {n}-{f} [] :vector-i64 {lit(c[f])})')
            defs.append(f'(defn- {n}-sealed [] :vector-i64 {lit(c["ct"] + c["tag"])})')
            if c['valid']:
                checks.append(f'(and (same? (gcm/seal ({n}-key) ({n}-iv) ({n}-aad) ({n}-msg)) ({n}-sealed)) '
                              f'(same? (gcm/open ({n}-key) ({n}-iv) ({n}-aad) ({n}-sealed)) ({n}-msg)))')
            else:
                checks.append(f'(refused? (gcm/open ({n}-key) ({n}-iv) ({n}-aad) ({n}-sealed)))')
        terms.append(f'     (if (and {" ".join(checks)}) {1 << bit} 0)  ; {flag}: ' + ' '.join(str(c['id']) for c in cs))
    bodies[grp] = terms
for i, (k, out) in enumerate(FIPS):
    defs.append(f'(defn- g-fips{i}-key [] :vector-i64 {lit(k)})')
    defs.append(f'(defn- g-fips{i}-out [] :vector-i64 {lit(h(out))})')
defs.append(f'(defn- g-fips-pt [] :vector-i64 {lit(PT)})')
fips = ' '.join(f'(same? (a/encrypt (a/schedule (g-fips{i}-key)) (g-fips-pt)) (g-fips{i}-out))' for i in range(3))

expect = {g: (1 << len(f)) - 1 for g, f in GROUPS.items()}
expect['a'] |= 12  # bits 2 and 3 below
src = f''';; aes.native-gate -- AES (FIPS 197) and AES-GCM (SP 800-38D) known answers (JUN-553,
;; JUN-352). Generated by tools/gen_gate.py from Project Wycheproof (test/aes/
;; wycheproof_gcm.cljk) and FIPS 197 Appendix C; each case is re-checked against
;; tools/reference.py when written. A valid case must seal to the published bytes and
;; open back; an invalid one must open to [-1]. Bytes are vector literals.
;; Three groups, each its own image (an image does not reclaim memory):
;;   group-a returns {expect['a']}: 1 Ktv, 2 Pseudorandom (every key size), 4 FIPS 197 Appendix C
;;           for 128, 192 and 256 bits, 8 the S-box equals its definition
;;   group-b returns {expect['b']}: 1 SmallIv, 2 LongIv, 4 SpecialCase
;;   group-c returns {expect['c']}: 1 CounterWrap, 2 ModifiedTag, 4 ZeroLengthIv
(ns aes.native-gate
  (:require [aes.core :as a] [aes.gcm :as gcm])
  (:export [group-a group-b group-c]))

(defn- cat [x :vector-i64 y :vector-i64] :vector-i64
  (let [n (vector-count x) out (vector-alloc (+ n (vector-count y)))]
    (loop [i 0] (if (= i (vector-count out)) out
      (let [z (vector-assoc! out i (if (< i n) (vector-at x i) (vector-at y (- i n))))] (recur (+ i 1)))))))
(defn- same? [x :vector-i64 y :vector-i64] :bool
  (and (= (vector-count x) (vector-count y))
       (loop [i 0] (if (= i (vector-count x)) true (if (= (vector-at x i) (vector-at y i)) (recur (+ i 1)) false)))))
(defn- refused? [v :vector-i64] :bool (and (= (vector-count v) 1) (= (vector-at v 0) -1)))

(defn- g-xt [a :i64] :i64 (if (>= a 128) (bit-xor (bit-and (* a 2) 255) 27) (* a 2)))
(defn- g-mul [x :i64 y :i64] :i64
  (loop [a x b y r 0] (if (= b 0) r (recur (g-xt a) (quot b 2) (if (= (rem b 2) 1) (bit-xor r a) r)))))
(defn- g-inv [x :i64] :i64
  (if (= x 0) 0 (loop [k 0 r 1] (if (= k 254) r (recur (+ k 1) (g-mul r x))))))
(defn- g-rotl8 [b :i64 n :i64] :i64 (bit-and (bit-or (i64-shift-left b n) (i64-shift-right b (- 8 n))) 255))
(defn- g-sbox-ok? [] :bool
  ;; FIPS 197 section 5.1.1: the inverse in GF(2^8), then b ^ rotl1 ^ rotl2 ^ rotl3 ^ rotl4 ^ 0x63
  (loop [i 0]
    (if (= i 256) true
      (let [b (g-inv i)
            s (bit-xor (bit-xor (bit-xor b (g-rotl8 b 1)) (bit-xor (g-rotl8 b 2) (g-rotl8 b 3))) (bit-xor (g-rotl8 b 4) 99))]
        (if (= (vector-at (a/sbox) i) s) (recur (+ i 1)) false)))))

{chr(10).join(defs)}

(defn group-a [] :i64
  (+
{chr(10).join(bodies['a'])}
     (if (and {fips}) 4 0)
     (if (g-sbox-ok?) 8 0)))

(defn group-b [] :i64
  (+
{chr(10).join(bodies['b'])}
     ))

(defn group-c [] :i64
  (+
{chr(10).join(bodies['c'])}
     ))
'''
open(sys.argv[1], 'w').write(src)
print('expected', expect, 'cases', sum(len(cs) for g in GROUPS.values() for _, cs in g))
