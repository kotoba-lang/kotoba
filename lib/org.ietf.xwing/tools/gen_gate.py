#!/usr/bin/env python3
"""Write kotoba/xwing/native_gate.kotoba from the X-Wing draft's own test vectors.

Dev tool, not part of the library. Standard library only.

    python3 -I tools/gen_gate.py kotoba/xwing/native_gate.kotoba

test/test-vectors.json is spec/test-vectors.json of
https://github.com/dconnolly/draft-connolly-cfrg-xwing-kem at commit
984c2f7a93b8f8d8f8073ebb53f9f4ce50b5babd, unchanged; its SHA-256 is written into
the gate's header. Bytes are vector literals of at most 64 items; there are no
strings.
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VECTORS = os.path.join(os.path.dirname(HERE), 'test', 'test-vectors.json')
data = open(VECTORS, 'rb').read()
SHA = hashlib.sha256(data).hexdigest()
vs = json.loads(data)
assert len(vs) == 3
h = bytes.fromhex
for v in vs:
    pk, ct = h(v['pk']), h(v['ct'])
    assert v['sk'] == v['seed'] and len(pk) == 1216 and len(ct) == 1120

def lit(b):
    b = list(b)
    parts = [f'(vector-i64 {" ".join(map(str, b[i:i + 64]))})' for i in range(0, len(b), 64)]
    while len(parts) > 1:
        parts = [f'(cat {parts[i]} {parts[i + 1]})' if i + 1 < len(parts) else parts[i] for i in range(0, len(parts), 2)]
    return parts[0]

defs = []
for i, v in enumerate(vs):
    for f in ('seed', 'eseed', 'ss', 'pk', 'ct'):
        defs.append(f'(defn- g-{i}-{f} [] :vector-i64 {lit(h(v[f]))})')

def vector_bits(i):
    return f'''  (+ (if (same? (xw/public-key (g-{i}-seed)) (g-{i}-pk)) 1 0)
     (if (same? (xw/encapsulate (g-{i}-pk) (g-{i}-eseed)) (cat (g-{i}-ss) (g-{i}-ct))) 2 0)
     (if (same? (xw/decapsulate (g-{i}-seed) (g-{i}-ct)) (g-{i}-ss)) 4 0)'''

src = f''';; xwing.native-gate -- X-Wing known answers from the draft's test vectors (AWAI-102,
;; JUN-352). Generated by tools/gen_gate.py from test/test-vectors.json (the draft
;; repository's spec/test-vectors.json at 984c2f7a, sha256 {SHA[:16]}...).
;; Bytes are vector literals. An image holds 10-20 X25519 multiplications, so each
;; vector is its own group:
;;   group-a, group-b: vector 0 / 1 returns 7: 1 public key from the seed, 2 the
;;           encapsulation (ss || ct) from pk and eseed, 4 decapsulation to ss
;;   group-c returns 63: vector 2 as above (1, 2, 4); 8 a changed ML-KEM ciphertext byte
;;           and 16 a changed X25519 ciphertext byte decapsulate to another 32-byte
;;           secret, not a refusal; 32 wrong lengths and non-byte values give empty
(ns xwing.native-gate
  (:require [xwing.core :as xw])
  (:export [group-a group-b group-c]))

(defn- cat [x :vector-i64 y :vector-i64] :vector-i64
  (let [n (vector-count x) out (vector-alloc (+ n (vector-count y)))]
    (loop [i 0] (if (= i (vector-count out)) out
      (let [z (vector-assoc! out i (if (< i n) (vector-at x i) (vector-at y (- i n))))] (recur (+ i 1)))))))
(defn- g-slice [v :vector-i64 start :i64 n :i64] :vector-i64
  (loop [i 0 out (vector-alloc n)] (if (= i n) out (recur (+ i 1) (vector-assoc! out i (vector-at v (+ start i)))))))
(defn- g-set [v :vector-i64 at :i64 x :i64] :vector-i64
  (let [out (g-slice v 0 (vector-count v))] (vector-assoc! out at x)))
(defn- g-flip [v :vector-i64 at :i64] :vector-i64 (g-set v at (bit-xor (vector-at v at) 1)))
(defn- same? [x :vector-i64 y :vector-i64] :bool
  (and (= (vector-count x) (vector-count y))
       (loop [i 0] (if (= i (vector-count x)) true (if (= (vector-at x i) (vector-at y i)) (recur (+ i 1)) false)))))
(defn- g-other? [v :vector-i64 ss :vector-i64] :bool (and (= (vector-count v) 32) (not (same? v ss))))
(defn- g-empty? [v :vector-i64] :bool (= (vector-count v) 0))

{chr(10).join(defs)}

(defn group-a [] :i64
{vector_bits(0)}))

(defn group-b [] :i64
{vector_bits(1)}))

(defn group-c [] :i64
{vector_bits(2)}
     (if (g-other? (xw/decapsulate (g-2-seed) (g-flip (g-2-ct) 100)) (g-2-ss)) 8 0)
     (if (g-other? (xw/decapsulate (g-2-seed) (g-flip (g-2-ct) 1100)) (g-2-ss)) 16 0)
     (if (and (g-empty? (xw/public-key (g-slice (g-2-seed) 0 31)))
              (g-empty? (xw/encapsulate (g-slice (g-2-pk) 0 1215) (g-2-eseed)))
              (g-empty? (xw/encapsulate (g-2-pk) (g-slice (g-2-eseed) 0 63)))
              (g-empty? (xw/encapsulate (g-2-pk) (g-set (g-2-eseed) 0 256)))
              (g-empty? (xw/decapsulate (g-2-seed) (g-slice (g-2-ct) 0 1119)))
              (g-empty? (xw/decapsulate (g-set (g-2-seed) 3 -1) (g-2-ct)))) 32 0)))
'''
open(sys.argv[1], 'w').write(src)
print('sha256', SHA)
