#!/usr/bin/env python3
"""Write kotoba/chacha20/native_gate.kotoba from tools/reference.py.

Dev tool, not part of the library. Standard library only.

    python3 -I tools/gen_gate.py kotoba/chacha20/native_gate.kotoba

Each value the RFC 8439 text prints is asserted here against the reference. Bytes are
vector literals of at most 64 items (the compiler's limit), so the gate has no strings.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reference import block, encrypt, poly1305, seal

h = bytes.fromhex
SUN = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it."
K0 = bytes(range(32))
B232 = block(K0, 1, h('000000090000004a00000000'))
E242 = encrypt(K0, 1, h('000000000000004a00000000'), SUN)
PK = h('85d6be7857556d337f4452fe42d506a80103808afb0db2fd4abff6af4149f51b')
PM = b'Cryptographic Forum Research Group'
AK, AN, AA = h('808182838485868788898a8b8c8d8e8f909192939495969798999a9b9c9d9e9f'), h('070000004041424344454647'), h('50515253c0c1c2c3c4c5c6c7')
S282 = seal(AK, AN, AA, SUN)
assert B232.hex() == ('10f1e7e4d13b5915500fdd1fa32071c4c7d1f4c733c068030422aa9ac3d46c4e'
                     'd2826446079faa0914c2d705d98b02a2b5129cd1de164eb9cbd083e8a2503c4e')
assert E242[:16].hex() == '6e2e359a2568f98041ba0728dd0d6981' and E242[-2:].hex() == '874d'
assert poly1305(PK, PM).hex() == 'a8061dc1305136c6c22b8baf0c0127a9'
assert S282[:16].hex() == 'd31a8d34648e60db7b86afbc53ef7ec2' and S282[-16:].hex() == '1ae10b594f09e26a7e902ecbd0600691'
z = bytes(16)
A3 = [(bytes([2]) + bytes(15) + z, b'\xff' * 16, '03' + '00' * 15),
      (bytes([2]) + bytes(15) + b'\xff' * 16, bytes([2]) + bytes(15), '03' + '00' * 15),
      (bytes([1]) + bytes(15) + z, b'\xff' * 16 + b'\xf0' + b'\xff' * 15 + b'\x11' + bytes(15), '05' + '00' * 15),
      (bytes([1]) + bytes(15) + z, b'\xff' * 16 + b'\xfb' + b'\xfe' * 15 + b'\x01' * 16, '00' * 16),
      (bytes([2]) + bytes(15) + z, b'\xfd' + b'\xff' * 15, 'fa' + 'ff' * 15)]
for k, m, t in A3:
    assert poly1305(k, m).hex() == t
# lengths around the 16-byte block and the 64-byte keystream block
LENS = [0, 1, 15, 16, 17, 63, 64, 65, 129]
PAT = bytes((7 * i + 3) % 256 for i in range(129))
EMPTY = seal(AK, AN, b'', b'')

def lit(b):
    b = list(b)
    if not b:
        return '(vector-i64)'
    parts = [f'(vector-i64 {" ".join(map(str, b[i:i + 64]))})' for i in range(0, len(b), 64)]
    expr = parts[0]
    for p in parts[1:]:
        expr = f'(cat {expr} {p})'
    return expr

defs = []
def d(name, b):
    defs.append(f'(defn- {name} [] :vector-i64 {lit(b)})')
for name, b in [('k0', K0), ('n232', h('000000090000004a00000000')), ('b232', B232), ('n242', h('000000000000004a00000000')),
                ('sun', SUN), ('e242', E242), ('pk', PK), ('pm', PM), ('ptag', poly1305(PK, PM)), ('ak', AK), ('an', AN),
                ('aa', AA), ('s282', S282), ('empty-sealed', EMPTY), ('pat', PAT)]:
    d('g-' + name, b)
for i, (k, m, t) in enumerate(A3):
    d(f'g-a3-{i}-k', k); d(f'g-a3-{i}-m', m); d(f'g-a3-{i}-t', h(t))
for n in LENS:
    d(f'g-mac-{n}', poly1305(AK, PAT[:n])); d(f'g-seal-{n}', seal(AK, AN, AA, PAT[:n]))

a3 = ' '.join(f'(same? (p/mac (g-a3-{i}-k) (g-a3-{i}-m)) (g-a3-{i}-t))' for i in range(len(A3)))
macs = ' '.join(f'(same? (p/mac (g-ak) (g-slice (g-pat) 0 {n})) (g-mac-{n}))' for n in LENS)
seals = ' '.join(f'(same? (a/seal (g-ak) (g-an) (g-aa) (g-slice (g-pat) 0 {n})) (g-seal-{n}))' for n in LENS)
opens = ' '.join(f'(same? (a/open (g-ak) (g-an) (g-aa) (g-seal-{n})) (g-slice (g-pat) 0 {n}))' for n in LENS)

src = f''';; chacha20.native-gate -- RFC 8439 known answers for the native ChaCha20, Poly1305 and
;; AEAD (AWAI-117). Generated by tools/gen_gate.py from tools/reference.py; every value
;; the RFC prints is asserted against the RFC text there. Bytes are vector literals.
;;
;; main returns a bitmask, 127 is a pass:
;;   1 section 2.3.2 block            2 section 2.4.2 encryption (114 bytes)
;;   4 section 2.5.2 Poly1305 and Appendix A.3 #5-#9 (the h >= p reductions)
;;   8 section 2.8.2 AEAD seal, and open gives the plaintext back
;;  16 a changed ciphertext byte, tag byte, AAD byte or nonce byte opens to [-1]
;;  32 Poly1305 and seal/open at 0, 1, 15, 16, 17, 63, 64, 65 and 129 bytes, and an
;;     empty plaintext with empty AAD
;;  64 bad key or nonce lengths and non-byte values are refused; a sealed input
;;     shorter than a tag opens to [-1]
(ns chacha20.native-gate
  (:require [chacha20.core :as c] [chacha20.poly1305 :as p] [chacha20.aead :as a])
  (:export [main]))

(defn- cat [x :vector-i64 y :vector-i64] :vector-i64
  (let [n (vector-count x) out (vector-alloc (+ n (vector-count y)))]
    (loop [i 0] (if (= i (vector-count out)) out
      (let [z (vector-assoc! out i (if (< i n) (vector-at x i) (vector-at y (- i n))))] (recur (+ i 1)))))))
(defn- g-slice [v :vector-i64 start :i64 n :i64] :vector-i64
  (loop [i 0 out (vector-alloc n)] (if (= i n) out (recur (+ i 1) (vector-assoc! out i (vector-at v (+ start i)))))))
(defn- g-set [v :vector-i64 at :i64 x :i64] :vector-i64
  (let [out (g-slice v 0 (vector-count v))] (vector-assoc! out at x)))
(defn- g-flip [v :vector-i64 at :i64] :vector-i64 (g-set v at (bit-xor (vector-at v at) 1)))
(defn- same? [x :vector-i64 y :vector-i64] :bool
  (and (= (vector-count x) (vector-count y))
       (loop [i 0] (if (= i (vector-count x)) true (if (= (vector-at x i) (vector-at y i)) (recur (+ i 1)) false)))))
(defn- refused? [v :vector-i64] :bool (and (= (vector-count v) 1) (= (vector-at v 0) -1)))

{chr(10).join(defs)}

(defn- g-tampered [] :bool
  (and (refused? (a/open (g-ak) (g-an) (g-aa) (g-flip (g-s282) 0)))
       (refused? (a/open (g-ak) (g-an) (g-aa) (g-flip (g-s282) 113)))
       (refused? (a/open (g-ak) (g-an) (g-aa) (g-flip (g-s282) 120)))
       (refused? (a/open (g-ak) (g-an) (g-flip (g-aa) 3) (g-s282)))
       (refused? (a/open (g-ak) (g-flip (g-an) 11) (g-aa) (g-s282)))))

(defn- g-refusals [] :bool
  (and (= (vector-count (a/seal (g-slice (g-ak) 0 31) (g-an) (g-aa) (g-sun))) 0)
       (= (vector-count (a/seal (g-ak) (g-slice (g-an) 0 11) (g-aa) (g-sun))) 0)
       (= (vector-count (a/seal (g-ak) (g-an) (g-aa) (g-set (g-sun) 4 256))) 0)
       (= (vector-count (a/seal (g-ak) (g-an) (g-set (g-aa) 0 -1) (g-sun))) 0)
       (refused? (a/open (g-slice (g-ak) 0 31) (g-an) (g-aa) (g-s282)))
       (refused? (a/open (g-ak) (g-an) (g-aa) (g-slice (g-s282) 0 15)))))

(defn main [] :i64
  (+ (if (same? (c/block (g-k0) 1 (g-n232)) (g-b232)) 1 0)
     (if (same? (c/xor-stream (g-k0) 1 (g-n242) (g-sun)) (g-e242)) 2 0)
     (if (and (same? (p/mac (g-pk) (g-pm)) (g-ptag)) {a3}) 4 0)
     (if (and (same? (a/seal (g-ak) (g-an) (g-aa) (g-sun)) (g-s282))
              (same? (a/open (g-ak) (g-an) (g-aa) (g-s282)) (g-sun))) 8 0)
     (if (g-tampered) 16 0)
     (if (and {macs} {seals} {opens}
              (same? (a/seal (g-ak) (g-an) (vector-i64) (vector-i64)) (g-empty-sealed))
              (same? (a/open (g-ak) (g-an) (vector-i64) (g-empty-sealed)) (vector-i64))) 32 0)
     (if (g-refusals) 64 0)))
'''
open(sys.argv[1], 'w').write(src)
