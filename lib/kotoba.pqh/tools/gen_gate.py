#!/usr/bin/env python3
"""Write kotoba/pqh/native_gate.kotoba, known answers for the native pqh-v1 hybrid KEM.

Dev tool, not part of the library. Standard library only.

    python3 -I tools/gen_gate.py kotoba/pqh/native_gate.kotoba

The expected shared secrets are computed here with Python's hmac/hashlib HKDF from
values that do not depend on the native code: X25519 from RFC 7748 section 6.1 (the
x25519 reference asserts them), and ML-KEM-768 shared secrets and ciphertexts from the
ACVP vectors in ../gov.nist.mlKem/test/mlkem/acvp/. The combiner follows
src/kotoba/lang/pqh/pq.cljk (combine-shared-secrets). Bytes are vector literals.
"""
import hashlib
import hmac
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(LIB, 'org.ietf.x25519', 'tools'))
from reference import x25519  # noqa: E402

h = bytes.fromhex
SALT = b'etzhayyim/pqh-v1/kem'
INFO = b'AWAI-117 native gate'

def hkdf(ikm, salt, info, n):
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    okm, t, i = b'', b'', 1
    while len(okm) < n:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest(); okm += t; i += 1
    return okm[:n]

def combine(ss_x, ss_k, eph_pub, ct, rx_pub, r_ek, info):
    return hkdf(ss_x + ss_k, SALT, hashlib.sha256(eph_pub + ct + rx_pub + r_ek).digest() + info, 32)

def acvp(name):
    t = open(os.path.join(LIB, 'gov.nist.mlKem', 'test', 'mlkem', 'acvp', name + '.cljk')).read()
    rows = {}
    for tc, body in re.findall(r'\[(\d+)((?:\s+(?:"[^"]*"|true|false|nil))+)\]', t):
        rows[int(tc)] = [x.strip('"') for x in re.findall(r'"[^"]*"|true|false|nil', body)]
    return rows

NINE = bytes([9]) + bytes(31)
ALICE, BOB = h('77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a'), h('5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb')
A_PUB, B_PUB = x25519(ALICE, NINE), x25519(BOB, NINE)
SS_X = x25519(ALICE, B_PUB)
assert SS_X.hex() == '4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742' == x25519(BOB, A_PUB).hex()

enc, dec, kg, ekc = acvp('encaps'), acvp('decaps'), acvp('keygen'), acvp('ek_check')
EK26, M26, C26, K26 = (h(v) for v in enc[26])
DK86, C86, K86 = h(dec[86][0]), h(dec[86][1]), h(dec[86][2])
EK86 = DK86[1152:2336]
D26, Z26 = h(kg[26][0]), h(kg[26][1])
BAD_EK = h(ekc[137][0]); assert ekc[137][1] == 'false'

ENC_OUT = combine(SS_X, K26, A_PUB, C26, B_PUB, EK26, INFO) + A_PUB + C26
DEC_OUT = combine(SS_X, K86, A_PUB, C86, B_PUB, EK86, INFO)
ENC_EMPTY_INFO = combine(SS_X, K26, A_PUB, C26, B_PUB, EK26, b'')
assert ENC_EMPTY_INFO != ENC_OUT[:32]

def lit(b):
    b = list(b)
    if not b:
        return '(vector-i64)'
    parts = [f'(vector-i64 {" ".join(map(str, b[i:i + 64]))})' for i in range(0, len(b), 64)]
    while len(parts) > 1:
        parts = [f'(cat {parts[i]} {parts[i + 1]})' if i + 1 < len(parts) else parts[i] for i in range(0, len(parts), 2)]
    return parts[0]

defs = [f'(defn- g-{n} [] :vector-i64 {lit(b)})' for n, b in [
    ('alice', ALICE), ('alice-pub', A_PUB), ('bob', BOB), ('bob-pub', B_PUB), ('info', INFO),
    ('ek26', EK26), ('m26', M26), ('enc-out', ENC_OUT), ('enc-empty-info', ENC_EMPTY_INFO),
    ('dk86', DK86), ('c86', C86), ('ek86', EK86), ('dec-out', DEC_OUT),
    ('d26', D26), ('z26', Z26), ('bad-ek', BAD_EK), ('zero', bytes(32))]]

src = f''';; pqh.native-gate -- known answers for the native pqh-v1 hybrid KEM (AWAI-117).
;; Generated by tools/gen_gate.py: the expected secrets are Python hmac/hashlib HKDF over
;; RFC 7748 section 6.1 X25519 values and ACVP ML-KEM-768 values (encapsulation tc 26,
;; decapsulation tc 86, keyGen tc 26, encapsulation-key check tc 137). Bytes are vector
;; literals. One image holds 10-20 X25519 multiplications, so there are three groups:
;;   group-a returns 7:  1 encapsulate gives the expected secret, ephemeral key and
;;           ciphertext; 2 decapsulate gives the expected secret; 4 the caller info is
;;           bound (empty info gives the other expected secret)
;;   group-b returns 15: from a fresh ML-KEM keyGen, 1 both sides agree; a changed
;;           2 ciphertext byte, 4 ephemeral key byte or 8 info byte gives a different
;;           secret, not a refusal
;;   group-c returns 15: refused (empty) are 1 a low-order recipient X25519 key, 2 a
;;           low-order ephemeral key, 4 wrong lengths and non-byte values, 8 an ML-KEM
;;           key that fails the FIPS 203 section 7.2 check
(ns pqh.native-gate
  (:require [pqh.hybrid :as hy] [mlkem.core :as k])
  (:export [group-a group-b group-c]))

(defn- cat [x :vector-i64 y :vector-i64] :vector-i64
  (let [n (vector-count x) out (vector-alloc (+ n (vector-count y)))]
    (loop [i 0] (if (= i (vector-count out)) out
      (let [z (vector-assoc! out i (if (< i n) (vector-at x i) (vector-at y (- i n))))] (recur (+ i 1)))))))
(defn- g-slice [v :vector-i64 start :i64 n :i64] :vector-i64
  (loop [i 0 out (vector-alloc n)] (if (= i n) out (recur (+ i 1) (vector-assoc! out i (vector-at v (+ start i)))))))
(defn- g-set [v :vector-i64 at :i64 x :i64] :vector-i64
  (let [out (g-slice v 0 (vector-count v))] (vector-assoc! out at x)))
(defn- g-flip [v :vector-i64 at :i64] :vector-i64 (g-set v at (bit-xor (vector-at v at) 1)))
(defn- same? [x :vector-i64 y :vector-i64] :bool
  (and (= (vector-count x) (vector-count y))
       (loop [i 0] (if (= i (vector-count x)) true (if (= (vector-at x i) (vector-at y i)) (recur (+ i 1)) false)))))
(defn- g-empty? [v :vector-i64] :bool (= (vector-count v) 0))

{chr(10).join(defs)}

(defn group-a [] :i64
  (+ (if (same? (hy/encapsulate (g-alice) (g-m26) (g-bob-pub) (g-ek26) (g-info)) (g-enc-out)) 1 0)
     (if (same? (hy/decapsulate (g-bob) (g-dk86) (g-alice-pub) (g-c86) (g-bob-pub) (g-ek86) (g-info)) (g-dec-out)) 2 0)
     (if (same? (g-slice (hy/encapsulate (g-alice) (g-m26) (g-bob-pub) (g-ek26) (vector-i64)) 0 32) (g-enc-empty-info)) 4 0)))

(defn group-b [] :i64
  (let [kp (k/keygen (g-d26) (g-z26)) ek (g-slice kp 0 1184) dk (g-slice kp 1184 2400)
        sent (hy/encapsulate (g-alice) (g-m26) (g-bob-pub) ek (g-info))
        ss (g-slice sent 0 32) eph (g-slice sent 32 32) ct (g-slice sent 64 1088)
        back (hy/decapsulate (g-bob) dk eph ct (g-bob-pub) ek (g-info))
        bad-ct (hy/decapsulate (g-bob) dk eph (g-flip ct 7) (g-bob-pub) ek (g-info))
        bad-eph (hy/decapsulate (g-bob) dk (g-flip eph 3) ct (g-bob-pub) ek (g-info))
        bad-info (hy/decapsulate (g-bob) dk eph ct (g-bob-pub) ek (g-flip (g-info) 0))]
    (+ (if (and (= (vector-count sent) 1152) (same? back ss)) 1 0)
       (if (and (= (vector-count bad-ct) 32) (not (same? bad-ct ss))) 2 0)
       (if (and (= (vector-count bad-eph) 32) (not (same? bad-eph ss))) 4 0)
       (if (and (= (vector-count bad-info) 32) (not (same? bad-info ss))) 8 0))))

(defn group-c [] :i64
  (+ (if (g-empty? (hy/encapsulate (g-alice) (g-m26) (g-zero) (g-ek26) (g-info))) 1 0)
     (if (g-empty? (hy/decapsulate (g-bob) (g-dk86) (g-zero) (g-c86) (g-bob-pub) (g-ek86) (g-info))) 2 0)
     (if (and (g-empty? (hy/encapsulate (g-slice (g-alice) 0 31) (g-m26) (g-bob-pub) (g-ek26) (g-info)))
              (g-empty? (hy/encapsulate (g-alice) (g-slice (g-m26) 0 31) (g-bob-pub) (g-ek26) (g-info)))
              (g-empty? (hy/encapsulate (g-alice) (g-m26) (g-bob-pub) (g-ek26) (g-set (g-info) 0 256)))
              (g-empty? (hy/decapsulate (g-bob) (g-dk86) (g-alice-pub) (g-slice (g-c86) 0 1087) (g-bob-pub) (g-ek86) (g-info)))
              (g-empty? (hy/decapsulate (g-bob) (g-dk86) (g-alice-pub) (g-c86) (g-bob-pub) (g-slice (g-ek86) 0 1183) (g-info)))) 4 0)
     (if (g-empty? (hy/encapsulate (g-alice) (g-m26) (g-bob-pub) (g-bad-ek) (g-info))) 8 0)))
'''
open(sys.argv[1], 'w').write(src)
