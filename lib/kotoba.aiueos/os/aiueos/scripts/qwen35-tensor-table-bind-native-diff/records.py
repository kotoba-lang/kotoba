#!/usr/bin/env python3
# usage: records.py HEADER.gguf OUT.h -- the offsets of each GGUF tensor record's name length, name, dimension count,
# first dimension, type and data offset in HEADER (made by tests/make_qwen35_header_fixture.py), relative to the end of
# the metadata, as a C table for driver.c. JUN-633.
import struct, sys
b = open(sys.argv[1], "rb").read()
tensors = struct.unpack_from("<Q", b, 8)[0]; n = struct.unpack_from("<Q", b, 16)[0]
SIZES = {0: 1, 1: 1, 2: 2, 3: 2, 4: 4, 5: 4, 6: 4, 7: 1, 10: 8, 11: 8, 12: 8}
def skip(p, t):
    if t in SIZES: return p + SIZES[t]
    if t == 8: return p + 8 + struct.unpack_from("<Q", b, p)[0]
    et, cnt = struct.unpack_from("<IQ", b, p); p += 12
    for _ in range(cnt): p = skip(p, et)
    return p
pos = 24
for _ in range(n):
    klen = struct.unpack_from("<Q", b, pos)[0]; t = struct.unpack_from("<I", b, pos + 8 + klen)[0]
    pos = skip(pos + 12 + klen, t)
meta_end = pos; rows = []
for _ in range(tensors):
    nlen = struct.unpack_from("<Q", b, pos)[0]; p = pos + 8 + nlen
    nd = struct.unpack_from("<I", b, p)[0]; dims = p + 4; after = dims + 8 * nd
    rows.append((pos - meta_end, pos + 8 - meta_end, p - meta_end, dims - meta_end, after - meta_end, after + 4 - meta_end))
    pos = after + 12
with open(sys.argv[2], "w") as f:
    f.write("/* generated by records.py: name-length, name, ndims, dim0, type, offset per record (from the metadata end) */\n")
    f.write("static const uint64_t rec_off[%d][6] = {\n" % len(rows))
    for r in rows: f.write("  {%d, %d, %d, %d, %d, %d},\n" % r)
    f.write("};\n#define RECORDS %d\n#define METADATA_END %d\n#define TABLE_END %d\n" % (len(rows), meta_end, pos))
print("records", len(rows), "metadata_end", meta_end, "table_end", pos)
