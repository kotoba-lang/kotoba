#!/usr/bin/env python3
"""Generate os/aiueos/aiueos/session/app_catalog.kotoba from app_catalog.json (JUN-811).

Each title and body is ASCII, packed 8 characters of 7 bits into one i64 word, so a catalog entry costs one `case`
arm per 8 characters instead of one per character: the desktop kernel is within a few KiB of the 2 MiB code cap.
`check` fails when the committed .kotoba differs from what this script would write.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SESSION = HERE.parent / "aiueos" / "session"
SOURCE = SESSION / "app_catalog.json"
TARGET = SESSION / "app_catalog.kotoba"
PER_WORD = 8


def pack(text, label):
    raw = text.encode("ascii")
    if any(c > 127 for c in raw):
        raise ValueError(label + ": not 7-bit ASCII")
    words = []
    for start in range(0, len(raw), PER_WORD):
        word = 0
        for k, c in enumerate(raw[start:start + PER_WORD]):
            word |= c << (7 * k)
        words.append(word)
    return words


def arms(rows):
    # rows: {id: [words]} -> nested case on id then word index
    out = []
    for app, words in rows.items():
        inner = " ".join("%d %d" % (j, w) for j, w in enumerate(words))
        out.append("    %d (case j %s 0)" % (app, inner))
    return "\n".join(out)


def render():
    doc = json.loads(SOURCE.read_text())
    if doc.get("schema") != "aiueos.native-app-catalog.v1":
        raise ValueError("unknown catalog schema")
    apps = doc["apps"]
    ids = [a["id"] for a in apps]
    if ids != list(range(1, len(ids) + 1)):
        raise ValueError("app ids must be 1..N")
    titles = {a["id"]: pack(a["title"], "title %d" % a["id"]) for a in apps}
    bodies = {a["id"]: pack(a["body"], "body %d" % a["id"]) for a in apps}
    tl = " ".join("%d %d" % (a["id"], len(a["title"])) for a in apps)
    bl = " ".join("%d %d" % (a["id"], len(a["body"])) for a in apps)
    return f""";; GENERATED by os/aiueos/scripts/gen-app-catalog.py from app_catalog.json. Do not edit by hand.
(ns aiueos.session.app-catalog
  (:export [app-count app-title-length app-title-codepoint app-body-length app-body-codepoint]))
;; Exact scalar Kotoba counterpart of the compatibility CLJK catalogue.
;; Cards describe unregistered services; they do not execute dapps or infer.
;; Text is 7-bit ASCII packed 8 characters per word (character k of a word is bits 7k..7k+6).
(defn app-count [] :i64 {len(apps)})
(defn app-title-length [id :i64] :i64 (case id {tl} 0))
(defn app-body-length [id :i64] :i64 (case id {bl} 0))
(defn- pick [w :i64 k :i64] :i64
  (mod (quot w (case k 0 1 1 128 2 16384 3 2097152 4 268435456 5 34359738368 6 4398046511104 7 562949953421312 1)) 128))
(defn- title-word [id :i64 j :i64] :i64
  (case id
{arms(titles)} 0))
(defn- body-word [id :i64 j :i64] :i64
  (case id
{arms(bodies)} 0))
(defn app-title-codepoint [id :i64 index :i64] :i64
  (pick (title-word id (quot index {PER_WORD})) (mod index {PER_WORD})))
(defn app-body-codepoint [id :i64 index :i64] :i64
  (pick (body-word id (quot index {PER_WORD})) (mod index {PER_WORD})))
"""


def main():
    text = render()
    if sys.argv[1:] == ["check"]:
        if TARGET.read_text() != text:
            print("AIUEOS_APP_CATALOG_STALE: run gen-app-catalog.py")
            return 1
        print("AIUEOS_APP_CATALOG_OK apps=%d" % len(json.loads(SOURCE.read_text())["apps"]))
        return 0
    TARGET.write_text(text)
    print("AIUEOS_APP_CATALOG_WRITTEN")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
