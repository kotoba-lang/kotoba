# usage: gen-object.py OUT -- writes kotoba/device-result-text.kotoba (byte strings as little-endian 64-bit words). JUN-554.
import sys
REC = {'mac': (0, 6), 'pub': (8, 64), 'boot': (72, 8), 'model': (80, 32), 'nonce': (112, 16), 'sig': (128, 64)}
NUMS = ['token', 'second-token', 'generated-tokens', 'decode-tokens', 'model-load-cycles', 'first-token-cycles',
        'decode-cycles', 'inference-cycles', 'vector-bits', 'worker-threads', 'tsc-hz']
def words(s):
    b = s.encode(); return [(int.from_bytes(b[i:i+8], 'little'), len(b[i:i+8])) for i in range(0, len(b), 8)]
STEPS = []
def step(expr):
    STEPS.append(expr); return f"a{len(STEPS) - 1}"
def text(s, at):
    for w, k in words(s): at = step(f"(put p n {at} {w} {k})")
    return at
def hexf(name, at):
    off, ln = REC[name]; return step(f"(put-hex p n {at} {off * 65536 + ln * 256})")
def num(name, at):
    v = step(f"(num {NUMS.index(name)})"); return step(f"(put-dec p n {at} {v})")
def chain(build):
    STEPS.clear(); last = build()
    binds = "\n        ".join(f"a{i} {e}" for i, e in enumerate(STEPS))
    return f"(let [{binds}]\n    {last})"
def node(at): return hexf('mac', text('aiueos-k16-', at))
def canonical():
    at = text('aiueos-k16-result-v2', '0')
    at = node(text('\n', at))
    for f in ['pub', 'boot', 'model']: at = hexf(f, text('\n', at))
    at = text('\nQwen3.8-27B-UD-IQ3_XXS.gguf\n2', at)
    for f in NUMS: at = num(f, text('\n', at))
    return hexf('nonce', text('\n', at))
def body():
    at = node(text('{"node":"', '0'))
    at = hexf('pub', text('","public-key":"', at)); at = hexf('boot', text('","boot":"', at))
    at = hexf('model', text('","model-sha256":"', at))
    at = text('","model":"Qwen3.8-27B-UD-IQ3_XXS.gguf","protocol":2,"token":', at)
    at = num('token', at)
    for f in NUMS[1:]: at = num(f, text(f',"{f}":', at))
    at = hexf('nonce', text(',"nonce":"', at)); at = hexf('sig', text('","signature":"', at))
    return text('"}', at)
src = f''';; The signed canonical text and the JSON body of kernel/device_result.c's aiueos_device_result_http_request in Kotoba
;; (JUN-554): what the K16 qualification result asserts and how it is sent. The C fills a 288-byte record with the raw
;; values and keeps the key, the nonce, the hash, the signature and the HTTP framing.
;;
;; text(rec, rec-len, mode, out, cap): mode 0 the canonical text that is hashed and signed, mode 1 the JSON body. Returns
;;   the length written, or 0 when the text does not fit in out[0..cap) (the C's bounded_buffer refused it then and the
;;   caller used nothing), the record is shorter than 288 bytes or longer than 512, cap is above 16384, out is null, or
;;   mode is neither. Hex is lowercase; decimals are the C's put_decimal of a uint64_t (unsigned, no leading zero).
;; The record: MAC 0..6, public key X || Y 8..72, boot id 72..80, model SHA-256 80..112, nonce 112..128, signature
;;   128..192 (mode 1 only), then big-endian u64 (device_result.c's ctx_number) {', '.join(NUMS)} from 192.
;;
;; The record is copied into this object's .bss 0 first, and .bss 1 holds a decimal's digits (amu ADR 0385 / 0387). Like the C's, not reentrant.
;; Generated by scripts/device-result-text-diff/gen-object.py; edit that, not this.
;; Built by the Amu aiueos kernel object route at amu 65359a09, fuel 4194304.
(ns aiueos.device-result-text
  (:export [kotoba_aiueos_device_result_text]))
(defn- bss-addr-0-288 [] :i64 0)
(defn- bss-addr-1-24 [] :i64 0)
(defn- canonical? [x :i64] :bool (= (u64-shift-right x 32) 0))
(defn- r [i :i64] :i64 (kernel-load-u8 (bss-addr-0-288) 288 i))
(defn- copy-rec [rec :i64 rn :i64 i :i64] :i64
  (if (>= i 288) 0 (let [v (kernel-load-u8 rec rn i) w (kernel-store-u8 (bss-addr-0-288) 288 i v)] (copy-rec rec rn (+ (+ i 1) (* 0 w))))))
(defn- num-at [at :i64 k :i64 acc :i64] :i64
  (if (>= k 8) acc (num-at at (+ k 1) (+ (* acc 256) (r (+ at k))))))
(defn- num [k :i64] :i64 (num-at (+ 192 (* 8 k)) 0 0))
;; one byte at out[at]; -1 once anything has not fit
(defn- put-byte [p :i64 n :i64 at :i64 v :i64] :i64
  (if (or (< at 0) (>= at n)) -1 (let [w (kernel-store-u8-16k p n at v)] (+ (+ at 1) (* 0 w)))))
(defn- put-bytes [p :i64 n :i64 at :i64 w :i64 ki :i64] :i64
  (let [k (u64-shift-right ki 8) i (bit-and ki 255)]
    (if (>= i k) at (let [a (put-byte p n at (bit-and (u64-shift-right w (* 8 i)) 255))] (put-bytes p n a w (+ ki 1))))))
(defn- put [p :i64 n :i64 at :i64 w :i64 k :i64] :i64 (put-bytes p n at w (* k 256)))
(defn- nib [x :i64] :i64 (if (< x 10) (+ 48 x) (+ 87 x)))
;; the record's bytes off..off+len as lowercase hex; oi is off << 16 | len << 8 | i
(defn- put-hex [p :i64 n :i64 at :i64 oi :i64] :i64
  (let [off (u64-shift-right oi 16) len (bit-and (u64-shift-right oi 8) 255) i (bit-and oi 255)]
    (if (>= i len) at
      (let [b (r (+ off i)) a (put-byte p n at (nib (u64-shift-right b 4))) c (put-byte p n a (nib (bit-and b 15)))]
        (put-hex p n c (+ oi 1))))))
;; x as an unsigned decimal: x / 10 is (x >> 1) / 5 for every uint64_t; the digits are written low-first into .bss 1
;; and emitted high-first (a self-call that passes the output base from inside a branch is not admitted)
(defn- digits [x :i64 k :i64] :i64
  (let [q (quot (u64-shift-right x 1) 5) w (kernel-store-u8 (bss-addr-1-24) 24 k (+ 48 (- x (* q 10))))]
    (if (= q 0) (+ (+ k 1) (* 0 w)) (digits q (+ k 1)))))
(defn- emit-digits [p :i64 n :i64 at :i64 k :i64] :i64
  (if (< k 0) at (let [a (put-byte p n at (kernel-load-u8 (bss-addr-1-24) 24 k))] (emit-digits p n a (- k 1)))))
(defn- put-dec [p :i64 n :i64 at :i64 x :i64] :i64 (emit-digits p n at (- (digits x 0) 1)))
(defn- canonical-text [p :i64 n :i64] :i64
  {chain(canonical)})
(defn- body-text [p :i64 n :i64] :i64
  {chain(body)})
(defn kotoba_aiueos_device_result_text [rec :i64 rec-len :i64 mode :i64 out :i64 cap :i64] :i64
  (if (or (= out 0) (= rec 0) (not (canonical? rec-len)) (not (canonical? cap)) (< rec-len 288) (> rec-len 512) (> cap 16384)
          (and (not= mode 0) (not= mode 1))) 0
    (let [c (copy-rec rec rec-len 0)
          len (if (= (+ mode (* 0 c)) 0) (canonical-text out cap) (body-text out cap))]
      (if (< len 0) 0 len))))
'''
open(sys.argv[1], 'w').write(src)
