#!/usr/bin/env python3
# usage: offsets.py HEADER.gguf OUT.h -- the offsets of each GGUF metadata entry's key length, key bytes, value type and
# first value bytes in HEADER (made by tests/make_qwen35_header_fixture.py), as a C table for driver.c. JUN-633.
import struct, sys
b = open(sys.argv[1], "rb").read()
n = struct.unpack_from("<Q", b, 16)[0]
pos = 24; rows = []
SIZES = {0: 1, 1: 1, 2: 2, 3: 2, 4: 4, 5: 4, 6: 4, 7: 1, 10: 8, 11: 8, 12: 8}
def skip(p, t):
    if t in SIZES: return p + SIZES[t]
    if t == 8: return p + 8 + struct.unpack_from("<Q", b, p)[0]
    et, cnt = struct.unpack_from("<IQ", b, p); p += 12
    for _ in range(cnt): p = skip(p, et)
    return p
for _ in range(n):
    klen = struct.unpack_from("<Q", b, pos)[0]
    t = struct.unpack_from("<I", b, pos + 8 + klen)[0]
    rows.append((pos, pos + 8, klen, pos + 8 + klen, pos + 12 + klen))
    pos = skip(pos + 12 + klen, t)
with open(sys.argv[2], "w") as f:
    f.write("/* generated by offsets.py: key-length, key, key bytes, type, value offsets per entry */\n")
    f.write("static const uint64_t entry_off[%d][5] = {\n" % len(rows))
    for r in rows: f.write("  {%d, %d, %d, %d, %d},\n" % r)
    f.write("};\n#define ENTRIES %d\n#define METADATA_END %d\n" % (len(rows), pos))
print("entries", len(rows), "metadata_end", pos)
