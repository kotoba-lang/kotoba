#!/usr/bin/env python3
"""Write kotoba/x25519/native_gate.kotoba from tools/reference.py.

Dev tool, not part of the library. Standard library only.

    python3 -I tools/gen_gate.py kotoba/x25519/native_gate.kotoba

Every expected value is computed here by the reference and asserted against the
RFC 7748 text where the RFC publishes it. Bytes are written as vector literals (no
strings), so the gate also compiles for the x86_64 KX64 profile.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reference import x25519, clamp

h = bytes.fromhex
NINE = bytes([9]) + bytes(31)
V1K, V1U = h('a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4'), h('e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c')
V2K, V2U = h('4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d'), h('e5210f12786811d3f4b7959d0538ae2c31dbe7106fc03c3efc4cd549c715a493')
ALICE, BOB = h('77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a'), h('5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb')
ORDER8 = h('e0eb7a7c3b41b8ae1656e3faf19fc46ada098deb9c32b1fd866205165f49b800')

V1 = x25519(V1K, V1U); V2 = x25519(V2K, V2U)
A, B = x25519(ALICE, NINE), x25519(BOB, NINE); K = x25519(ALICE, B)
IT1 = x25519(NINE, NINE)
# the RFC 7748 text (sections 5.2 and 6.1)
assert V1.hex() == 'c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552'
assert V2.hex() == '95cbde9476e8907d7aade45cb4b873f88b595a68799fa152e6f8f7647aac7957'
assert A.hex() == '8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a'
assert B.hex() == 'de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f'
assert K.hex() == '4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742' == x25519(BOB, A).hex()
assert IT1.hex() == '422c8e7a6227d7bca1350b3e2bb7279f7897b87bb6854b783c60e80311ae3079'
V1U_TOP = bytes(V1U[:31]) + bytes([V1U[31] | 128])
assert x25519(V1K, V1U_TOP) == V1 and x25519(V1K, ORDER8) == bytes(32) and x25519(V1K, bytes(32)) == bytes(32)

def lit(name, b):
    return f'(defn- {name} [] :vector-i64 (vector-i64 {" ".join(map(str, b))}))'

out = [''';; x25519.native-gate -- RFC 7748 known answers for the native X25519 (AWAI-117).
;; Generated by tools/gen_gate.py from tools/reference.py; every value the RFC
;; publishes is asserted against the RFC text there. Bytes are vector literals.
;;
;; One image holds only 10-20 scalar multiplications before its heap runs out (the
;; field copies a vector per write and nothing is reclaimed inside an image), so the
;; gate is three groups, each run as its own image through a one-line entry:
;;   group-a returns 15: 1 section 5.2 vector 1, 2 vector 2, 4 bit 255 of u is
;;           ignored (vector 1 with that bit set), 8 the clamped scalar
;;   group-b returns 7:  1 Alice's public key, 2 Bob's, 4 both shared secrets
;;           (section 6.1)
;;   group-c returns 15: 1 one round of the section 5.2 iteration, 2 u = 0 and
;;           4 a point of order 8 give all zeros and are not contributory, 8 the
;;           section 6.1 secret is contributory
;; The thousand-round iteration is not run natively (it needs 1000 multiplications).
(ns x25519.native-gate
  (:require [x25519.core :as x])
  (:export [group-a group-b group-c]))

(defn- same? [a :vector-i64 b :vector-i64] :bool
  (and (= (vector-count a) (vector-count b))
       (loop [i 0] (if (= i (vector-count a)) true (if (= (vector-at a i) (vector-at b i)) (recur (+ i 1)) false)))))
''']
for name, b in [('nine', NINE), ('v1-k', V1K), ('v1-u', V1U), ('v1-u-top', V1U_TOP), ('v1-out', V1), ('v1-clamped', clamp(V1K)),
                ('v2-k', V2K), ('v2-u', V2U), ('v2-out', V2), ('alice', ALICE), ('bob', BOB), ('alice-pub', A),
                ('bob-pub', B), ('shared', K), ('it1', IT1), ('zero', bytes(32)), ('order8', ORDER8)]:
    out.append(lit('g-' + name, b))
out.append('''
(defn group-a [] :i64
  (+ (if (same? (x/x25519-bytes (g-v1-k) (g-v1-u)) (g-v1-out)) 1 0)
     (if (same? (x/x25519-bytes (g-v2-k) (g-v2-u)) (g-v2-out)) 2 0)
     (if (same? (x/x25519-bytes (g-v1-k) (g-v1-u-top)) (g-v1-out)) 4 0)
     (if (same? (x/clamp (g-v1-k)) (g-v1-clamped)) 8 0)))

(defn group-b [] :i64
  (+ (if (same? (x/public-key (g-alice)) (g-alice-pub)) 1 0)
     (if (same? (x/public-key (g-bob)) (g-bob-pub)) 2 0)
     (if (and (same? (x/x25519-bytes (g-alice) (g-bob-pub)) (g-shared))
              (same? (x/x25519-bytes (g-bob) (g-alice-pub)) (g-shared))) 4 0)))

(defn group-c [] :i64
  (+ (if (same? (x/x25519-bytes (g-nine) (g-nine)) (g-it1)) 1 0)
     (let [s (x/x25519-bytes (g-v1-k) (g-zero))] (if (and (same? s (g-zero)) (not (x/contributory? s))) 2 0))
     (let [s (x/x25519-bytes (g-v1-k) (g-order8))] (if (and (same? s (g-zero)) (not (x/contributory? s))) 4 0))
     (if (x/contributory? (g-shared)) 8 0)))
''')
open(sys.argv[1], 'w').write('\n'.join(out))
